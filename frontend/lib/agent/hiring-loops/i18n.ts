export const HL_MESSAGES: Record<HlLocale, Record<HlKey, string>> = { en, hi, te }

export function hlLocale(v: unknown): HlLocale {
  return v === 'hi' || v === 'te' ? v : 'en'
}

/** Translate with `{name}` slots (missing → English → the key). Pure. */
export function hlt(locale: HlLocale | string, key: HlKey | string, params?: Record<string, string | number | null | undefined>): string {
  const l = hlLocale(locale)
  const tpl = (HL_MESSAGES[l] as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key
  if (!params) return tpl
  return tpl.replace(/\{(\w+)\}/g, (m, k: string) => (params[k] === undefined || params[k] === null ? m : String(params[k])))
}

/** Neutral evidence summary for one case, in the reader's language. Pure. */
export function evidenceSummary(locale: HlLocale | string, c: {
  trust: { score: number; incidents: number; top: string[] } | null
  similarity: { max_score: number; cluster_size: number } | null
  ai: { level: 'none' | 'low' | 'medium' | 'high'; labels: string[] } | null
  review: 'unreviewed' | 'reviewed' | 'cleared' | 'flagged'
}): string {
  const out: string[] = []
  if (c.trust) {
    out.push(c.trust.incidents > 0
      ? hlt(locale, 'ev.trust', { score: c.trust.score, count: c.trust.incidents, top: c.trust.top.slice(0, 3).join(', ') || '—' })
      : hlt(locale, 'ev.trustNone', { score: c.trust.score }))
  }
  if (c.similarity && c.similarity.cluster_size > 1) {
    out.push(hlt(locale, 'ev.similar', { pct: Math.round(c.similarity.max_score * 100), count: c.similarity.cluster_size - 1 }))
  }
  if (c.ai && c.ai.level !== 'none') out.push(hlt(locale, 'ev.ai', { level: hlt(locale, `level.${c.ai.level}`), labels: c.ai.labels.slice(0, 3).join(', ') || '—' }))
  if (c.review !== 'unreviewed') out.push(hlt(locale, 'ev.review', { status: hlt(locale, `review.${c.review}`) }))
  out.push(hlt(locale, 'ev.note'))
  return out.join(' ')
}
