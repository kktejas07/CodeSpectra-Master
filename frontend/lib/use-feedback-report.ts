'use client'

import { useCallback } from 'react'
import type { InterviewFeedback } from '@/lib/interview-service'

interface FeedbackReportData {
  interviewType: string
  roleId: string
  overallScore: number
  feedback: InterviewFeedback[]
  messages: Array<{
    role: 'interviewer' | 'candidate'
    content: string
    duration?: number
  }>
  proctorEvents?: Array<{ event_type: string; created_at: string }>
}

/**
 * Generate and download a PDF interview report using jsPDF.
 * Falls back to HTML download if jsPDF is not available.
 */
export function useFeedbackReport() {
  const downloadPdf = useCallback(async (data: FeedbackReportData) => {
    try {
      // Dynamic import of jsPDF (only loaded when needed)
      const { default: jsPDF } = await import('jspdf')
      const doc = new jsPDF()

      const pageWidth = doc.internal.pageSize.getWidth()
      let y = 20

      // Title
      doc.setFontSize(20)
      doc.setFont('helvetica', 'bold')
      doc.text('Interview Report', pageWidth / 2, y, { align: 'center' })
      y += 10

      doc.setFontSize(11)
      doc.setFont('helvetica', 'normal')
      doc.text(`Type: ${data.interviewType}  |  Role: ${data.roleId}`, pageWidth / 2, y, { align: 'center' })
      y += 6
      doc.text(`Date: ${new Date().toLocaleDateString()}`, pageWidth / 2, y, { align: 'center' })
      y += 6
      doc.text(`Overall Score: ${data.overallScore}%`, pageWidth / 2, y, { align: 'center' })
      y += 12

      // Overall score bar
      doc.setFillColor(230, 230, 230)
      doc.rect(20, y, pageWidth - 40, 8, 'F')
      const barColor = data.overallScore >= 70 ? [34, 197, 94] : data.overallScore >= 40 ? [234, 179, 8] : [239, 68, 68]
      doc.setFillColor(barColor[0], barColor[1], barColor[2])
      doc.rect(20, y, (pageWidth - 40) * (data.overallScore / 100), 8, 'F')
      y += 14

      // Separator
      doc.setDrawColor(200, 200, 200)
      doc.line(20, y, pageWidth - 20, y)
      y += 8

      // Feedback dimensions
      doc.setFontSize(14)
      doc.setFont('helvetica', 'bold')
      doc.text('Detailed Feedback', 20, y)
      y += 8

      for (const item of data.feedback) {
        if (y > 260) { doc.addPage(); y = 20 }

        doc.setFontSize(11)
        doc.setFont('helvetica', 'bold')
        doc.text(`${item.dimension} — ${item.score}%`, 20, y)
        y += 5

        // Score bar
        doc.setFillColor(230, 230, 230)
        doc.rect(20, y, 80, 4, 'F')
        const dimColor = item.score >= 70 ? [34, 197, 94] : item.score >= 40 ? [234, 179, 8] : [239, 68, 68]
        doc.setFillColor(dimColor[0], dimColor[1], dimColor[2])
        doc.rect(20, y, 80 * (item.score / 100), 4, 'F')
        y += 7

        doc.setFontSize(9)
        doc.setFont('helvetica', 'normal')
        const feedbackLines = doc.splitTextToSize(item.feedback, pageWidth - 40)
        doc.text(feedbackLines, 20, y)
        y += feedbackLines.length * 4 + 2

        if (item.suggestions.length > 0) {
          doc.setFont('helvetica', 'italic')
          for (const s of item.suggestions) {
            const lines = doc.splitTextToSize(`• ${s}`, pageWidth - 44)
            doc.text(lines, 22, y)
            y += lines.length * 4
          }
        }
        y += 4
      }

      // Transcript
      if (data.messages.length > 0) {
        if (y > 240) { doc.addPage(); y = 20 }
        doc.setFontSize(14)
        doc.setFont('helvetica', 'bold')
        doc.text('Transcript', 20, y)
        y += 8

        doc.setFontSize(8)
        doc.setFont('helvetica', 'normal')
        for (const msg of data.messages) {
          if (y > 275) { doc.addPage(); y = 20 }
          const prefix = msg.role === 'interviewer' ? 'Interviewer: ' : 'Candidate: '
          const lines = doc.splitTextToSize(prefix + msg.content, pageWidth - 40)
          doc.text(lines, 20, y)
          y += lines.length * 3.5 + 1
        }
      }

      // Footer
      doc.setFontSize(7)
      doc.setFont('helvetica', 'italic')
      doc.text('Generated by CodeSpectra AI Interview System', pageWidth / 2, doc.internal.pageSize.getHeight() - 10, { align: 'center' })

      doc.save(`interview-report-${data.interviewType}-${Date.now()}.pdf`)
    } catch {
      // Fallback to HTML if jsPDF fails
      downloadHtmlFallback(data)
    }
  }, [])

  return { downloadPdf }
}

function downloadHtmlFallback(data: FeedbackReportData) {
  const html = `<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>Interview Report</title>
<style>
  body { font-family: -apple-system, system-ui, sans-serif; max-width: 800px; margin: 0 auto; padding: 40px 20px; color: #1a1a1a; }
  h1 { border-bottom: 2px solid #3b82f6; padding-bottom: 8px; }
  .score-badge { display: inline-block; padding: 4px 12px; border-radius: 9999px; font-weight: 700; font-size: 14px; }
  .high { background: #dcfce7; color: #166534; }
  .mid { background: #fef9c3; color: #854d0e; }
  .low { background: #fecaca; color: #991b1b; }
  .dimension { margin: 16px 0; padding: 16px; border: 1px solid #e5e7eb; border-radius: 8px; }
  .bar { height: 8px; background: #e5e7eb; border-radius: 4px; margin-top: 8px; }
  .bar-fill { height: 100%; border-radius: 4px; }
  .suggestions { margin-top: 8px; padding-left: 16px; }
  .suggestions li { margin: 4px 0; font-size: 14px; }
  .meta { color: #6b7280; font-size: 13px; margin-top: 24px; }
  @media print { body { padding: 0; } }
</style></head><body>
  <h1>Technical Interview Report</h1>
  <p><strong>Type:</strong> ${data.interviewType} | <strong>Role:</strong> ${data.roleId}</p>
  <p><strong>Overall Score:</strong> <span class="score-badge ${data.overallScore >= 70 ? 'high' : data.overallScore >= 40 ? 'mid' : 'low'}">${data.overallScore}%</span></p>
  <p><strong>Date:</strong> ${new Date().toLocaleDateString()}</p>
  <hr />
  ${data.feedback.map(f => `
    <div class="dimension">
      <h3>${f.dimension} <span class="score-badge ${f.score >= 70 ? 'high' : f.score >= 40 ? 'mid' : 'low'}">${f.score}%</span></h3>
      <div class="bar"><div class="bar-fill" style="width:${f.score}%;background:${f.score >= 70 ? '#22c55e' : f.score >= 40 ? '#eab308' : '#ef4444'}"></div></div>
      <p>${f.feedback}</p>
      <ul class="suggestions">${f.suggestions.map(s => `<li>${s}</li>`).join('')}</ul>
    </div>
  `).join('')}
  <hr />
  <h3>Transcript</h3>
  ${data.messages.map(m => `<p><strong>${m.role === 'interviewer' ? 'Interviewer' : 'Candidate'}:</strong> ${m.content}${m.duration ? ` (${m.duration}s)` : ''}</p>`).join('')}
  <p class="meta">Generated by CodeSpectra AI Interview System</p>
  <script>window.print()</script>
</body></html>`
  const blob = new Blob([html], { type: 'text/html' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `interview-report-${data.interviewType}-${Date.now()}.html`
  a.click()
  URL.revokeObjectURL(url)
}
