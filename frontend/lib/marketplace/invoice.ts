/**
 * Printable HTML invoice for a marketplace order (the buyer prints / saves as PDF from the
 * browser). Every value is escaped. Tax shown as one GST (INR) or sales-tax (USD) line at the
 * order's snapshot rate — included in prices or added, as charged.
 */
import { escapeHtml } from '@/lib/safe-html'
import { formatMinor } from './pricing'
import type { OrderDoc } from './order-doc'

export function buildInvoiceHtml(o: OrderDoc, sellers: Record<string, { name: string; gstin?: string | null }>, platform: { name: string; address?: string; gstin?: string | null }): string {
  const m = (n: number) => escapeHtml(formatMinor(n, o.currency))
  const pct = ((o.tax_bps ?? 0) / 100).toFixed(2).replace(/\.00$/, '')
  const taxLabel = o.currency === 'INR' ? `GST @ ${pct}%` : `Sales tax @ ${pct}%`
  const inclusive = o.prices_include_tax !== false
  const date = new Date(o.payment.paid_at || o.created_at).toISOString().slice(0, 10)
  const rows = o.lines.map((l) => {
    const s = sellers[l.seller_id]
    return `<tr><td>${escapeHtml(l.title)}${l.variant_name ? ` <span class="muted">(${escapeHtml(l.variant_name)})</span>` : ''}<div class="muted">Sold by ${escapeHtml(s?.name || 'Seller')}${s?.gstin ? ` · GSTIN ${escapeHtml(s.gstin)}` : ''}</div></td><td class="num">${l.qty}</td><td class="num">${m(l.unit_price)}</td><td class="num">${m(l.gross ?? l.unit_price * l.qty)}</td></tr>`
  }).join('')
  const addr = o.shipping_address
  const refunded = o.payment.refunded_total ?? 0
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Invoice ${escapeHtml(o.number)}</title>
<style>
:root{color-scheme:light}body{font:14px/1.5 -apple-system,BlinkMacSystemFont,"Segoe UI",Helvetica,Arial,sans-serif;color:#0f1729;background:#fff;margin:0;padding:32px 16px}
.wrap{max-width:780px;margin:0 auto}h1{font-size:22px;margin:0}.muted{color:#475569;font-size:12px}table{width:100%;border-collapse:collapse;margin-top:16px}
th,td{text-align:left;padding:8px 6px;border-bottom:1px solid #e2e8f0;vertical-align:top}th{font-size:12px;color:#475569;font-weight:600}.num{text-align:right;font-variant-numeric:tabular-nums;white-space:nowrap}
.tot td{border:none;padding:4px 6px}.grand td{font-weight:700;font-size:16px;border-top:2px solid #0f1729}.head{display:flex;justify-content:space-between;gap:24px;flex-wrap:wrap}
button{margin-top:24px;background:#2F5BE7;color:#fff;border:0;border-radius:999px;padding:10px 20px;font-weight:600;cursor:pointer}@media print{button{display:none}body{padding:0}}
</style></head><body><div class="wrap">
<div class="head"><div><h1>Tax invoice</h1><div class="muted">Invoice ${escapeHtml(o.number)} · ${escapeHtml(date)}</div></div>
<div style="text-align:right"><strong>${escapeHtml(platform.name)}</strong>${platform.address ? `<div class="muted">${escapeHtml(platform.address)}</div>` : ''}${platform.gstin ? `<div class="muted">GSTIN ${escapeHtml(platform.gstin)}</div>` : ''}</div></div>
<div class="head" style="margin-top:20px"><div><div class="muted">Billed to</div>${escapeHtml(addr?.name || o.buyer_email)}${addr ? `<div class="muted">${escapeHtml([addr.line1, addr.line2, addr.city, addr.state, addr.postal_code, addr.country].filter(Boolean).join(', '))}</div>` : ''}</div>
<div style="text-align:right"><div class="muted">Payment</div>${escapeHtml(o.payment.gateway === 'phonepe' ? 'PhonePe' : 'Card (Stripe)')} · ${escapeHtml(o.payment.status)}</div></div>
<table><thead><tr><th>Item</th><th class="num">Qty</th><th class="num">Unit price</th><th class="num">Amount</th></tr></thead><tbody>${rows}</tbody></table>
<table class="tot"><tbody>
<tr><td>Subtotal</td><td class="num">${m(o.subtotal)}</td></tr>
${o.discount_total ? `<tr><td>Discount${o.coupon ? ` (${escapeHtml(o.coupon.code)})` : ''}</td><td class="num">−${m(o.discount_total)}</td></tr>` : ''}
${o.shipping_total ? `<tr><td>Shipping</td><td class="num">${m(o.shipping_total)}</td></tr>` : ''}
${o.tax_total || o.tax_bps ? `<tr><td>${escapeHtml(taxLabel)}${inclusive ? ' (included)' : ''}</td><td class="num">${m(o.tax_total)}</td></tr>` : ''}
<tr class="grand"><td>Total paid</td><td class="num">${m(o.grand_total)}</td></tr>
${refunded ? `<tr><td>Refunded</td><td class="num">−${m(refunded)}</td></tr>` : ''}
</tbody></table>
<p class="muted" style="margin-top:24px">This invoice was generated by CodeSpectra marketplace. Keep it for your records.</p>
<button type="button" onclick="window.print()">Print or save as PDF</button>
</div></body></html>`
}
